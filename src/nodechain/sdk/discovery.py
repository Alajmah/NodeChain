"""Public Discovery and Marketplace Integration (v2.7.0).

Discovery adds reachability.
Discovery does not add trust.

NON-NEGOTIABLE RULES:
    Marketplace listing is not certification.
    Discovery index signature is not package trust.
    Registry reachability is not registry eligibility.
    Popularity is not reputation.
    Reputation is not trust.

Discovery is a proposal layer. Discovered registries become normal
FederatedRegistryConfig entries only after operator/profile approval.
"""

from __future__ import annotations

import hashlib
import json
import os
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


DISCOVERY_VERSION = "v1"

# Safety limits
MAX_INDEX_SIZE_BYTES = 10 * 1024 * 1024  # 10 MB
MAX_REGISTRIES_PER_INDEX = 500
MAX_PACKAGES_PER_INDEX = 10000


class DiscoveryError(Exception):
    """Raised when discovery index is corrupt, stale, or oversized."""


class MarketplacePolicyDenial(Exception):
    """Raised when organization policy denies a marketplace operation."""


# ── Marketplace Registry Listing ─────────────────────────────────────────────

@dataclass
class MarketplaceRegistryListing:
    """A single registry listing from a discovery index.

    This is informational only. It does NOT confer trust, eligibility,
    or certification. It proposes a registry for operator consideration.
    """
    registry_id: str
    base_url: str
    display_name: str = ""
    description: str = ""
    categories: list[str] = field(default_factory=list)
    claimed_publishers: list[str] = field(default_factory=list)
    claimed_packages: list[str] = field(default_factory=list)
    reputation_hint: str = ""  # informational, never authoritative
    discovery_metadata_digest: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "registry_id": self.registry_id,
            "base_url": self.base_url,
            "display_name": self.display_name,
            "description": self.description,
            "categories": self.categories,
            "claimed_publishers": self.claimed_publishers,
            "claimed_packages": self.claimed_packages,
            "reputation_hint": self.reputation_hint,
            "discovery_metadata_digest": self.discovery_metadata_digest,
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> MarketplaceRegistryListing:
        return cls(
            registry_id=d["registry_id"],
            base_url=d["base_url"],
            display_name=d.get("display_name", ""),
            description=d.get("description", ""),
            categories=d.get("categories", []),
            claimed_publishers=d.get("claimed_publishers", []),
            claimed_packages=d.get("claimed_packages", []),
            reputation_hint=d.get("reputation_hint", ""),
            discovery_metadata_digest=d.get("discovery_metadata_digest", ""),
        )

    def to_federation_config(self) -> Any:
        """Convert to a FederatedRegistryConfig for proposal (not auto-add).

        Claimed packages and publishers are informational only.
        They do NOT become allowlist restrictions.
        """
        from nodechain.sdk.federation import FederatedRegistryConfig
        return FederatedRegistryConfig(
            registry_id=self.registry_id,
            base_url=self.base_url,
            trust_level="remote_untrusted",  # always untrusted from discovery
            allowed_publishers=[],  # empty = all (claims are informational)
            allowed_packages=[],  # empty = all (claims are informational)
            priority=100,  # default lowest priority
            enabled=False,  # disabled until explicitly approved
        )


# ── Public Discovery Index ───────────────────────────────────────────────────

@dataclass
class PublicDiscoveryIndex:
    """A discovery index from a public source.

    Attributes:
        index_id: Unique identifier for this index
        source_url: URL where the index was fetched from
        generated_at: When the index was generated by its publisher
        registries: List of MarketplaceRegistryListing entries
        publishers: Known publisher fingerprints in this index
        packages: Known package IDs in this index
        index_digest: SHA-256 of the index content
        signature: Optional RSA-PSS-SHA256 signature of the index
        signer_fingerprint: Optional fingerprint of the signer
    """
    index_id: str
    source_url: str
    generated_at: str
    registries: list[MarketplaceRegistryListing] = field(default_factory=list)
    publishers: list[str] = field(default_factory=list)
    packages: list[str] = field(default_factory=list)
    index_digest: str = ""
    signature: str = ""
    signer_fingerprint: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "index_id": self.index_id,
            "source_url": self.source_url,
            "generated_at": self.generated_at,
            "registries": [r.to_dict() for r in self.registries],
            "publishers": self.publishers,
            "packages": self.packages,
            "index_digest": self.index_digest,
            "signature": self.signature,
            "signer_fingerprint": self.signer_fingerprint,
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> PublicDiscoveryIndex:
        return cls(
            index_id=d["index_id"],
            source_url=d.get("source_url", ""),
            generated_at=d.get("generated_at", ""),
            registries=[MarketplaceRegistryListing.from_dict(r) for r in d.get("registries", [])],
            publishers=d.get("publishers", []),
            packages=d.get("packages", []),
            index_digest=d.get("index_digest", ""),
            signature=d.get("signature", ""),
            signer_fingerprint=d.get("signer_fingerprint", ""),
        )


def compute_index_digest(data: dict[str, Any]) -> str:
    """Compute SHA-256 digest of discovery index data."""
    # Exclude signature and index_digest from the digest computation
    payload = {k: v for k, v in data.items() if k not in ("signature", "index_digest")}
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode()).hexdigest()


